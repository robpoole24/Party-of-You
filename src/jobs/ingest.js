/**
 * GSS parser (General Social Survey)
 * Handles SPSS .sav files from gss.norc.org
 * Key variables: party ID, political views, economic attitudes, confidence in institutions
 *
 * GSS core variables we extract:
 *   PARTYID  — party identification (0=Strong Dem → 6=Strong Rep, 7=Other)
 *   POLVIEWS — political views (1=Extremely liberal → 7=Extremely conservative)
 *   YEAR     — survey year
 *   CONFED   — confidence in federal government
 *   CLASS_   — subjective class identification
 *   SATFIN   — satisfaction with financial situation
 *   EQWLTH   — should government reduce income differences (1=Strongly agree → 7=Strongly disagree)
 *   UNION_   — union membership
 *   WRKSTAT  — employment status
 */
async function parseGSS(filePath, db) {
  const ext = path.extname(filePath).toLowerCase();
  let rows;

  if (ext === '.sav') {
    rows = await readSpssFile(filePath);
  } else if (ext === '.csv') {
    const content = fs.readFileSync(filePath, 'utf-8');
    rows = parse(content, { columns: true, skip_empty_lines: true });
    rows = rows.map(r => {
      const norm = {};
      Object.entries(r).forEach(([k, v]) => { norm[k.toUpperCase()] = v; });
      return norm;
    });
  } else {
    return { rows: 0, inserted: 0, errors: 0 };
  }

  let inserted = 0;
  let errors = 0;

  for (const row of rows) {
    try {
      const year = parseInt(row['YEAR']) || null;
      if (!year) continue;

      const politicalData = {};
      const gssVars = ['PARTYID', 'POLVIEWS', 'CONFED', 'CONLEGIS', 'TRUST',
                       'CLASS_', 'SATFIN', 'EQWLTH', 'UNION_', 'WRKSTAT',
                       'RINCOM16', 'EDUC', 'RACE', 'SEX', 'AGE', 'REGION'];
      gssVars.forEach(v => {
        if (row[v] !== undefined && row[v] !== null) {
          politicalData[v.toLowerCase().replace('_', '')] = row[v];
        }
      });

      const id = row['ID_'] || row['ID'] || row['CASEID'] || `gss-${year}-${inserted}`;

      await db.query(`
        INSERT INTO gss_survey_responses
          (respondent_id, year, party_id, political_views, political_data, source_file)
        VALUES ($1, $2, $3, $4, $5, $6)
        ON CONFLICT (respondent_id, source_file) DO NOTHING
      `, [
        String(id),
        year,
        row['PARTYID'] !== undefined ? parseInt(row['PARTYID']) : null,
        row['POLVIEWS'] !== undefined ? parseInt(row['POLVIEWS']) : null,
        JSON.stringify(politicalData),
        path.basename(filePath),
      ]);

      inserted++;
    } catch (e) {
      errors++;
      if (errors <= 3) console.warn(`  GSS row error: ${e.message}`);
    }
  }

  return { rows: rows.length, inserted, errors };
}

async function parseANES(filePath, db) {
  const ext = path.extname(filePath).toLowerCase();
  let rows;

  if (ext === '.sav') {
    console.log(`  Reading ANES SPSS file...`);
    rows = await readSpssFile(filePath);
  } else if (ext === '.csv' || ext === '.tsv') {
    const content = fs.readFileSync(filePath, 'utf-8');
    rows = parse(content, {
      columns: true,
      skip_empty_lines: true,
      delimiter: ext === '.tsv' ? '\t' : ',',
    });
    rows = rows.map(r => {
      const norm = {};
      Object.entries(r).forEach(([k, v]) => { norm[k.toUpperCase()] = v; });
      return norm;
    });
  } else {
    console.log(`  Skipping unsupported ANES format: ${ext}`);
    return { rows: 0, inserted: 0, errors: 0 };
  }

  let inserted = 0;
  let errors = 0;

  // ANES key variables (vary slightly between cumulative and time series)
  // Cumulative file: VCF prefix. Time series: V prefix.
  for (const row of rows) {
    try {
      // Detect variable naming convention
      const isCumulative = Object.keys(row).some(k => k.startsWith('VCF'));
      const prefix = isCumulative ? 'VCF' : 'V';

      // Year
      const year = parseInt(row[`${prefix}0004`] || row['YEAR'] || row['VCF0004']) || null;
      if (!year) continue;

      // Party identification (7-point scale)
      const partyId = row[`${prefix}0301`] || row[`${prefix}9008`] || null;

      // Liberal-conservative self-placement (7-point)
      const ideology = row[`${prefix}0803`] || null;

      // Presidential approval / thermometer
      const presTherm = row[`${prefix}0424`] || row[`${prefix}9218`] || null;

      // Turnout / voted
      const voted = row[`${prefix}0702`] || row[`${prefix}9010`] || null;

      const politicalData = {};
      ['VCF0301','VCF0803','VCF0424','VCF0702','VCF0606','VCF0618',
       'VCF9008','VCF9010','VCF9218'].forEach(v => {
        if (row[v] !== undefined) politicalData[v.toLowerCase()] = row[v];
      });

      const id = row['VCF0006'] || row['VERSION'] || row['CASEID'] || `anes-${year}-${inserted}`;

      await db.query(`
        INSERT INTO anes_survey_responses
          (respondent_id, year, party_id, ideology, voted,
           political_data, source_file)
        VALUES ($1, $2, $3, $4, $5, $6, $7)
        ON CONFLICT (respondent_id, source_file) DO NOTHING
      `, [
        String(id),
        year,
        partyId !== null ? String(partyId) : null,
        ideology !== null ? String(ideology) : null,
        voted !== null ? String(voted) : null,
        JSON.stringify(politicalData),
        path.basename(filePath),
      ]);

      inserted++;
    } catch (e) {
      errors++;
      if (errors <= 3) console.warn(`  ANES row error: ${e.message}`);
    }
  }

  return { rows: rows.length, inserted, errors };
}

