/**
 * Parses all MIT Election Lab CSV files into historical_election_results.
 * Handles all column name variations across file types:
 *   - 1976-2018-house.csv       (candidatevotes, totalvotes, party, stage)
 *   - 1976-2018-senate.csv      (same)
 *   - 1976-2016-president.csv   (candidatevotes, totalvotes, party, no stage)
 *   - 2024-senate-state.csv     (votes, party_simplified)
 *   - 2024-president-state.csv  (votes, party_simplified)
 *   - 2024-*-county.csv         (votes, party_simplified, county columns)
 * Upload all files to the same source folder — parser handles each.
 */
async function parseElectionHistory(filePath, db) {
  const filename = path.basename(filePath).toLowerCase();
  const content = fs.readFileSync(filePath, 'utf-8');
  const rows = parse(content, { columns: true, skip_empty_lines: true, trim: true });

  let inserted = 0;
  let errors = 0;
  let skipped = 0;

  // Detect file type from filename
  const is2024 = filename.includes('2024');
  const isCounty = filename.includes('county');
  const isPresident = filename.includes('president');
  const isSenate = filename.includes('senate');
  const isHouse = filename.includes('house');

  // Only process general election stage for 1976-2018 files
  // 2024 files don't have a stage column

  const BATCH = 500;
  for (let i = 0; i < rows.length; i += BATCH) {
    const batch = rows.slice(i, i + BATCH);

    for (const row of batch) {
      try {
        // ── Normalize stage ──
        // Skip primaries in historical files
        const stage = row.stage || row.STAGE || 'GEN';
        if (!is2024 && !stage.toUpperCase().includes('GEN')) {
          skipped++;
          continue;
        }

        // ── Normalize state ──
        const state = (row.state_po || row.STATE_PO || row.state || row.STATE || '').toUpperCase().trim().slice(0, 2);
        if (!state) continue;

        // ── Normalize year ──
        const year = parseInt(row.year || row.YEAR);
        if (!year || isNaN(year)) continue;

        // ── Normalize office ──
        let office = row.office || row.OFFICE || '';
        if (!office) {
          if (isHouse) office = 'US House';
          else if (isSenate) office = 'US Senate';
          else if (isPresident) office = 'President';
          else office = 'Unknown';
        }

        // ── Normalize district ──
        let district = row.district || row.DISTRICT || '';
        if (!district || district === 'NA') {
          district = (isSenate || isPresident) ? 'statewide' : '00';
        }
        district = String(district);

        // ── Normalize candidate ──
        const candidate = (row.candidate || row.CANDIDATE || 'Unknown').trim();

        // ── Normalize party ──
        // 2024 files use party_simplified, older files use party
        const rawParty = row.party_simplified || row.party_detailed || row.party || row.PARTY || '';
        const party = normalizeParty(rawParty);

        // ── Normalize votes ──
        // 2024 files use 'votes', older files use 'candidatevotes'
        const candidatevotes = parseInt(row.votes || row.candidatevotes || row.CANDIDATEVOTES || 0) || 0;
        const totalvotes = parseInt(row.totalvotes || row.total_votes || row.TOTALVOTES || 0) || 0;

        // ── County handling ──
        // For county files, append county to district to keep granularity
        let districtKey = district;
        if (isCounty) {
          const county = row.county_name || row.county || row.COUNTY || '';
          if (county) districtKey = `${district}-${county.toLowerCase().replace(/\s+/g, '_')}`;
        }

        await db.query(`
          INSERT INTO historical_election_results
            (state, district, year, office, candidate_name, party, votes, total_votes, source)
          VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9)
          ON CONFLICT (state, district, year, office, candidate_name)
          DO UPDATE SET
            votes = EXCLUDED.votes,
            total_votes = EXCLUDED.total_votes,
            party = EXCLUDED.party
        `, [
          state,
          districtKey,
          year,
          office,
          candidate,
          party,
          candidatevotes,
          totalvotes,
          `MIT Election Lab — ${path.basename(filePath)}`,
        ]);
        inserted++;
      } catch (e) {
        errors++;
        if (errors <= 5) console.warn(`  [${filename}] Row error: ${e.message}`);
      }
    }

    if (i > 0 && i % 10000 === 0) {
      console.log(`  Progress: ${i.toLocaleString()}/${rows.length.toLocaleString()} rows...`);
    }
  }

  console.log(`  [${filename}] ${rows.length.toLocaleString()} rows → ${inserted.toLocaleString()} inserted, ${skipped.toLocaleString()} skipped (primaries), ${errors} errors`);
  return { rows: rows.length, inserted, errors };
}

